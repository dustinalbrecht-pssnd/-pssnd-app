const naturalWeaponCache = new Map();

function naturalWeaponImage(w, src) {
  const style = w && NATURAL_WEAPON_STYLES[w.id];
  if (!style || !src || NATURAL_WEAPON_ORIGINALS.get(w.id) !== src) return src;
  if (naturalWeaponCache.has(w.id)) return naturalWeaponCache.get(w.id);
  const filter = (id, slopes, offset) =>
    '<filter id="' +
    id +
    '" x="0%" y="0%" width="100%" height="100%" color-interpolation-filters="sRGB"><feColorMatrix type="saturate" values="0"/><feComponentTransfer>' +
    slopes
      .map(
        (s, i) =>
          '<feFunc' + ['R', 'G', 'B'][i] + ' type="linear" slope="' + s + '" intercept="' + offset + '"/>',
      )
      .join('') +
    '<feFuncA type="linear" slope="0" intercept="1"/></feComponentTransfer></filter>';
  const image = '<image x="0" y="0" width="1024" height="512" href="' + src + '"';
  const regions = style.polygons
    .map((points) => '<polygon points="' + points.map((p) => p.join(',')).join(' ') + '"/>')
    .join('');
  const svg =
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 512" width="1024" height="512"><defs>' +
    filter('metal', style.metal, -0.02) +
    filter('polymer', style.body, style.offset) +
    '<clipPath id="material">' +
    regions +
    '</clipPath><mask id="outline" maskUnits="userSpaceOnUse" x="0" y="0" width="1024" height="512" style="mask-type:alpha">' +
    image +
    '/></mask></defs><g mask="url(#outline)">' +
    image +
    ' filter="url(#metal)"/>' +
    image +
    ' filter="url(#polymer)" clip-path="url(#material)"/></g></svg>';
  const result = 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(svg);
  naturalWeaponCache.set(w.id, result);
  return result;
}

