const ATTACHMENT_BY = Object.fromEntries(ATTACHMENTS.map((a) => [a.id, a]));

const CATALOG_CACHE = 'eupdate_weapon_catalog_v1';

let catalogPending = null,
  catalogResponse = '',
  catalogRevision = 0;

function applyWeaponCatalog(data) {
  if (!Array.isArray(data.weapons)) return;
  for (const a of [...(data.attachments || []), ...data.weapons.flatMap((w) => w.customAttachments || [])]) {
    if (!a.id || !a.slot) continue;
    ATTACHMENT_BY[a.id] = a;
    const i = ATTACHMENTS.findIndex((x) => x.id === a.id);
    if (i < 0) ATTACHMENTS.push(a);
    else ATTACHMENTS[i] = a;
  }
  for (const remote of data.weapons) {
    if (!remote.id || remote.game !== 'mw4' || !CLASS[remote.cls]) continue;
    const old = BY[remote.id],
      w = {
        ...old,
        ...remote,
        img: remote.img || old?.img || '',
        catalogAssigned: remote.managed === true || remote.catalogAssigned === true,
      };
    if (old) Object.assign(old, w);
    else {
      WM.push(w);
      BY[w.id] = w;
    }
  }
}

async function loadWeaponCatalog() {
  if (!API) return;
  if (catalogPending) return catalogPending;
  catalogPending = (async () => {
    const r = await fetch(API + '/api/catalog', { cache: 'no-store' });
    if (!r.ok) throw Error('Waffenkatalog nicht erreichbar');
    const response = await r.text();
    if (response === catalogResponse) return catalogRevision;
    applyWeaponCatalog(JSON.parse(response));
    renderBuilder();
    renderGunsmith();
    renderPicker();
    catalogResponse = response;
    return ++catalogRevision;
  })();
  try {
    return await catalogPending;
  } finally {
    catalogPending = null;
  }
}

