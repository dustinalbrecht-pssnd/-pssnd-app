export function groupName(name, language) {
  return language === 'en' && Object.hasOwn(GROUPS_EN, name) ? GROUPS_EN[name] : name;
}

export function settingValue(value, language) {
  const text = String(value ?? '');
  if (language !== 'en') return text;
  return text.split(' / ').map((part) => Object.hasOwn(VALUES_EN, part) ? VALUES_EN[part] : part).join(' / ');
}
